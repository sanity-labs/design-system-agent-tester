#!/usr/bin/env node
/**
 * generate-icon-registry.mjs
 *
 * Build-time script that reads the exports of @sanity/icons and generates
 * a type-only registry file. The output has ZERO runtime cost — no imports,
 * no re-exports, no barrel file. It emits:
 *
 *   1. A union type of all valid icon names (`SanityIconName`)
 *   2. A keyword → icon-name mapping for IDE-friendly discovery
 *   3. A typed helper that narrows a string to `SanityIconName` at compile time
 *
 * Usage:
 *   node generate-icon-registry.mjs                  # writes to stdout
 *   node generate-icon-registry.mjs --out registry.ts # writes to file
 *   node generate-icon-registry.mjs --out registry.ts --watch  # not implemented, but the idea
 *
 * Integrate into your build:
 *   "prebuild": "node generate-icon-registry.mjs --out src/generated/sanity-icons.ts"
 *
 * The generated file should be committed so consumers without @sanity/icons
 * installed still get autocomplete. Re-run whenever @sanity/icons is upgraded.
 */

import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const __dirname = dirname(fileURLToPath(import.meta.url));

// ---------------------------------------------------------------------------
// 1. Extract icon names from the installed @sanity/icons package
// ---------------------------------------------------------------------------

let allExports;
try {
  allExports = require("@sanity/icons");
} catch {
  console.error(
    "Error: @sanity/icons is not installed. Run `npm install @sanity/icons` first.",
  );
  process.exit(1);
}

const iconNames = Object.keys(allExports)
  .filter((name) => name.endsWith("Icon") && name !== "Icon")
  .sort();

console.error(`Found ${iconNames.length} icons in @sanity/icons`);

// ---------------------------------------------------------------------------
// 2. Build keyword index (base name fragments → icon names)
//    e.g. "chevron" → ["ChevronDownIcon", "ChevronLeftIcon", ...]
//    This is emitted as a type-level mapping so it's searchable in IDEs
//    without any runtime cost.
// ---------------------------------------------------------------------------

/**
 * Split a PascalCase icon name into lowercase keyword fragments.
 * "DoubleChevronDownIcon" → ["double", "chevron", "down"]
 */
function extractKeywords(name) {
  const base = name.replace(/Icon$/, "");
  // Split on uppercase boundaries
  return base
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2")
    .toLowerCase()
    .split(/\s+/)
    .filter(Boolean);
}

const keywordMap = new Map();
for (const name of iconNames) {
  for (const kw of extractKeywords(name)) {
    if (!keywordMap.has(kw)) keywordMap.set(kw, []);
    keywordMap.get(kw).push(name);
  }
}

// Sort keywords alphabetically for stable output
const sortedKeywords = [...keywordMap.keys()].sort();

// ---------------------------------------------------------------------------
// 3. Generate the TypeScript source
// ---------------------------------------------------------------------------

const lines = [];

lines.push(`/**`);
lines.push(` * Auto-generated by generate-icon-registry.mjs`);
lines.push(` * Source: @sanity/icons (${iconNames.length} icons)`);
lines.push(` * Generated: ${new Date().toISOString()}`);
lines.push(` *`);
lines.push(` * DO NOT EDIT — re-run the generator after upgrading @sanity/icons:`);
lines.push(` *   node generate-icon-registry.mjs --out src/generated/sanity-icons.ts`);
lines.push(` *`);
lines.push(` * This file has ZERO runtime cost. It contains only types and a`);
lines.push(` * compile-time assertion helper. Nothing is imported or executed.`);
lines.push(` */`);
lines.push(``);

// -- Union type of all icon names --
lines.push(`/**`);
lines.push(` * Union of every icon exported by @sanity/icons.`);
lines.push(` * Use this to get autocomplete when referencing icon names as strings.`);
lines.push(` *`);
lines.push(` * @example`);
lines.push(` * import type { SanityIconName } from './sanity-icons'`);
lines.push(` *`);
lines.push(` * function getIcon(name: SanityIconName) {`);
lines.push(` *   // TypeScript autocompletes all ${iconNames.length} icon names here`);
lines.push(` * }`);
lines.push(` */`);
lines.push(`export type SanityIconName =`);
for (let i = 0; i < iconNames.length; i++) {
  const sep = i === iconNames.length - 1 ? ";" : "";
  lines.push(`  | '${iconNames[i]}'${sep}`);
}
lines.push(``);

// -- Base name type (without "Icon" suffix) --
lines.push(`/**`);
lines.push(` * Same as SanityIconName but without the "Icon" suffix.`);
lines.push(` * Useful for config objects, serialized data, or shorter notation.`);
lines.push(` *`);
lines.push(` * @example`);
lines.push(` * const config: { icon: SanityIconBaseName } = { icon: 'Edit' } // ✓ autocomplete`);
lines.push(` */`);
lines.push(`export type SanityIconBaseName =`);
for (let i = 0; i < iconNames.length; i++) {
  const baseName = iconNames[i].replace(/Icon$/, "");
  const sep = i === iconNames.length - 1 ? ";" : "";
  lines.push(`  | '${baseName}'${sep}`);
}
lines.push(``);

// -- Keyword lookup type (for documentation / searchability) --
lines.push(`/**`);
lines.push(` * Keyword → icon name mapping for discoverability.`);
lines.push(` * Hover over a keyword in your IDE to see which icons match.`);
lines.push(` *`);
lines.push(` * @example`);
lines.push(` * // Hover over 'arrow' to see: ArrowDownIcon | ArrowLeftIcon | ...`);
lines.push(` * type ArrowIcons = IconsByKeyword['arrow']`);
lines.push(` */`);
lines.push(`export interface IconsByKeyword {`);
for (const kw of sortedKeywords) {
  const names = keywordMap.get(kw);
  lines.push(`  ${kw}: ${names.map((n) => `'${n}'`).join(" | ")};`);
}
lines.push(`}`);
lines.push(``);

// -- Compile-time assertion helper --
lines.push(`/**`);
lines.push(` * Compile-time assertion that a string is a valid icon name.`);
lines.push(` * Returns the string narrowed to SanityIconName — zero runtime cost.`);
lines.push(` *`);
lines.push(` * @example`);
lines.push(` * import { iconName } from './sanity-icons'`);
lines.push(` * import { EditIcon } from '@sanity/icons' // still a direct import — tree-shakes`);
lines.push(` *`);
lines.push(` * // Validates at compile time that 'EditIcon' exists:`);
lines.push(` * const name = iconName('EditIcon')  // ✓ typed as 'EditIcon'`);
lines.push(` * const bad  = iconName('FooIcon')   // ✗ TypeScript error`);
lines.push(` */`);
lines.push(`export function iconName<T extends SanityIconName>(name: T): T {`);
lines.push(`  return name;`);
lines.push(`}`);
lines.push(``);

// -- Compile-time assertion for base names --
lines.push(`/**`);
lines.push(` * Same as iconName() but accepts the short form without "Icon" suffix.`);
lines.push(` */`);
lines.push(`export function iconBaseName<T extends SanityIconBaseName>(name: T): T {`);
lines.push(`  return name;`);
lines.push(`}`);
lines.push(``);

// -- Total count as a const for documentation --
lines.push(`/** Total number of icons available in @sanity/icons. */`);
lines.push(`export const SANITY_ICON_COUNT = ${iconNames.length} as const;`);
lines.push(``);

const output = lines.join("\n");

// ---------------------------------------------------------------------------
// 4. Write output
// ---------------------------------------------------------------------------

const outFlag = process.argv.indexOf("--out");
if (outFlag !== -1 && process.argv[outFlag + 1]) {
  const outPath = resolve(process.cwd(), process.argv[outFlag + 1]);
  writeFileSync(outPath, output, "utf-8");
  console.error(`Written to ${outPath}`);
} else {
  process.stdout.write(output);
}
